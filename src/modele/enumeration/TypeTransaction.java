package modele.enumeration;

/*
    * L'énumération TypeTransaction représente les types de transactions possibles dans le système.
    * Il y a deux types de transactions : DEPENSE et REVENU.
    * Chaque type de transaction est représenté par une constante de l'énumération.
    * L'énumération est utilisée pour catégoriser les transactions et faciliter la gestion des dépenses et des revenus.
*/
public enum TypeTransaction {
    DEPENSE,
    REVENU
}